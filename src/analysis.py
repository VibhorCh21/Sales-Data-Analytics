import pandas as pd


def get_monthly_revenue(df):
    """
    Calculate total revenue for each month.
    """

    df = df.copy()

    df["Month"] = df["InvoiceDate"].dt.to_period("M").astype(str)

    monthly_sales = (
        df.groupby("Month", as_index=False)["Revenue"]
        .sum()
        .sort_values("Month")
    )

    return monthly_sales


def get_top_products(df, limit=10):
    """
    Find top-selling products based on revenue.
    """

    top_products = (
        df.groupby(["StockCode", "Description"], as_index=False)
        .agg(
            Total_Quantity=("Quantity", "sum"),
            Total_Revenue=("Revenue", "sum")
        )
        .sort_values("Total_Revenue", ascending=False)
        .head(limit)
    )

    return top_products


def get_country_sales(df):
    """
    Calculate revenue generated by each country.
    """

    country_sales = (
        df.groupby("Country", as_index=False)["Revenue"]
        .sum()
        .sort_values("Revenue", ascending=False)
    )

    return country_sales


def get_top_customers(df, limit=10):
    """
    Find top customers based on total revenue.
    """

    customer_data = df.dropna(subset=["CustomerID"])

    top_customers = (
        customer_data.groupby("CustomerID", as_index=False)["Revenue"]
        .sum()
        .sort_values("Revenue", ascending=False)
        .head(limit)
    )

    return top_customers